"""MCP server exposing the IT support tools.

This process owns the data: it is the only component that opens the SQLite database.
The agent talks to it over the Model Context Protocol (stdio transport), so any other
MCP-capable client could reuse the same tools.

Tool input schemas are generated by the MCP SDK from the Python type hints below
(Literal -> enum, Field(description=...) -> parameter description, docstring -> tool description).
"""

from __future__ import annotations

import logging
from typing import Annotated, Any, Literal

from mcp.server.mcpserver import MCPServer
from pydantic import Field

from it_assistant import __version__
from it_assistant.config import Settings, get_settings
from it_assistant.data.database import Database
from it_assistant.tools import definitions as names
from it_assistant.tools.executor import ToolExecutor

logger = logging.getLogger(__name__)

Category = Literal["vpn", "network", "hardware", "software", "email", "account_access", "printer", "other"]
Priority = Literal["low", "medium", "high", "critical"]
StatusFilter = Literal["open", "closed", "all"]

EmployeeId = Annotated[str, Field(description="Employee ID, format EMP followed by 4 digits, e.g. EMP1024.")]


def create_server(settings: Settings | None = None) -> MCPServer:
    settings = settings or get_settings()
    database = Database(settings.database_path)
    database.initialize(settings.seed_dir)
    executor = ToolExecutor(database, settings)

    server = MCPServer(
        "it-support-tools",
        version=__version__,
        instructions="IT support tools for Contoso Ltd.: knowledge base, tickets, employees, system status.",
    )

    @server.tool(name=names.GET_EMPLOYEE_PROFILE)
    def get_employee_profile(employee_id: EmployeeId) -> dict[str, Any]:
        """Verify an employee and load their profile (name, department, location, assigned devices).
        Call this as soon as the user provides an employee ID. A successful call marks the employee
        as verified for the rest of the conversation; ticket lookup and ticket creation require it."""
        return executor.get_employee_profile({"employee_id": employee_id}).to_wire()

    @server.tool(name=names.SEARCH_KNOWLEDGE_BASE)
    def search_knowledge_base(
        query: Annotated[str, Field(description="Short keyword-rich search query, e.g. 'reset VPN password'.")],
    ) -> dict[str, Any]:
        """Search the internal IT knowledge base for how-to guides and troubleshooting steps (VPN,
        passwords, MFA, email, printers, Wi-Fi, software installs, laptops, etc.). Use for any
        'how do I...' or troubleshooting question. Answer only from returned article content."""
        return executor.search_knowledge_base({"query": query}).to_wire()

    @server.tool(name=names.LOOKUP_TICKETS)
    def lookup_tickets(
        employee_id: EmployeeId,
        ticket_id: Annotated[str, Field(description="Specific ticket ID if the user gave one, format INC + 6 digits. Empty for none.")] = "",
        status: Annotated[StatusFilter, Field(description="open (incl. in progress / on hold), closed, or all.")] = "all",
        keyword: Annotated[str, Field(description="Single keyword to match subject/description/category, e.g. 'laptop'. Empty for none.")] = "",
    ) -> dict[str, Any]:
        """Look up the verified employee's existing support tickets. Use for questions like 'what is
        the status of my laptop issue' or 'do I have open tickets'. All filters are optional."""
        args = {"ticket_id": ticket_id or None, "status": status, "keyword": keyword or None}
        return executor.lookup_tickets(args, employee_id or None).to_wire()

    @server.tool(name=names.CREATE_TICKET)
    def create_ticket(
        employee_id: EmployeeId,
        category: Category,
        subject: Annotated[str, Field(description="One-line summary, 5-120 characters.")],
        description: Annotated[str, Field(description="Details of the problem in the user's own terms, at least 15 characters.")],
        priority: Annotated[Priority, Field(description=(
            "low: minor inconvenience; medium: work impacted but workaround exists; "
            "high: cannot work; critical: many users or a security incident."))],
        confirmed_not_duplicate: Annotated[bool, Field(description=(
            "Set true ONLY if a previous call reported a possible duplicate and the user explicitly "
            "said this is a different issue."))] = False,
    ) -> dict[str, Any]:
        """Prepare a new IT support ticket. Only call this once you have a clear subject and a
        description with enough detail (what is happening, since when, error messages). The request
        is validated and checked for duplicate open tickets, then the user is asked to confirm - the
        ticket is NOT created by this tool. Never claim a ticket was created based on this result."""
        args = {
            "category": category, "subject": subject, "description": description,
            "priority": priority, "confirmed_not_duplicate": confirmed_not_duplicate,
        }
        return executor.prepare_ticket(args, employee_id or None).to_wire()

    @server.tool(name=names.COMMIT_TICKET)
    def commit_ticket(
        employee_id: EmployeeId,
        category: Category,
        subject: str,
        description: str,
        priority: Priority,
    ) -> dict[str, Any]:
        """Create a ticket in the ticketing system. Internal: only called by the application after the
        user has explicitly confirmed a draft. Not exposed to the language model."""
        draft = {"category": category, "subject": subject, "description": description, "priority": priority}
        return executor.commit_ticket(draft, employee_id).to_wire()

    @server.tool(name=names.CHECK_SYSTEM_STATUS)
    def check_system_status(
        system_name: Annotated[str, Field(description="Optional system name, e.g. 'VPN'. Empty to list all systems.")] = "",
    ) -> dict[str, Any]:
        """Check the current health of company IT systems (VPN, Email, Wi-Fi, SSO, HR Portal, etc.).
        Use when the user reports something is down or slow, before suggesting troubleshooting or
        raising a ticket - a known outage may already explain it."""
        return executor.check_system_status({"system_name": system_name}).to_wire()

    logger.info("MCP server ready (database=%s)", settings.database_path)
    return server
